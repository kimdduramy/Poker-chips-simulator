/** '場風 東' → '장풍 동', '立直' → '리치'. 모르는 이름은 그대로. */
export function yakuName(name: string): string {
  const wind = name.match(/^(場風|自風) (.)$/);
  if (wind) return `${wind[1] === '場風' ? '장풍' : '자풍'} ${WIND[wind[2]] ?? wind[2]}`;
  return YAKU[name] ?? name;
}

